/**
 * Embed Stitch HTML into a TS module so release APKs don't depend on
 * Asset/FileSystem loading (which often fails in production builds).
 *
 * Usage: node scripts/embed-stitch.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'stitch');
const outFile = path.join(__dirname, '..', 'src', 'stitch', 'html-bundle.ts');

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.html')).sort();
let out = '// AUTO-GENERATED by scripts/embed-stitch.js — do not edit by hand\n\n';
const map = [];

for (const f of files) {
  const key = f.replace(/\.html$/, '');
  const raw = fs.readFileSync(path.join(dir, f), 'utf8');
  const varName = 'HTML_' + key.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();
  out += `export const ${varName} = ${JSON.stringify(raw)};\n\n`;
  map.push([key, varName]);
}

out += 'export const STITCH_HTML: Record<string, string> = {\n';
for (const [k, v] of map) {
  out += `  ${JSON.stringify(k)}: ${v},\n`;
}
out += '};\n';

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`Embedded ${files.length} screens → ${outFile}`);
